const rel = (
  key: string,
  label: string,
  reference: string,
  extra: Partial<PlatformField> = {},
): PlatformField =>
  text(
    key,
    label,
    relationDescriptions[reference] || 'Связанный ресурс: ' + label.toLocaleLowerCase() + '.',
    { kind: 'relation', reference, ...extra },
  );
const choice = (
  key: string,
  label: string,
  choices: string[],
  extra: Partial<PlatformField> = {},
): PlatformField =>
  text(key, label, label + '.', {
    kind: 'enum',
    options: choices.map((value) => ({ value, label: value })),
    ...extra,
  });
const bool = (key: string, label: string, description: string, initial = false): PlatformField =>
  text(key, label, description, { kind: 'boolean', initial });
