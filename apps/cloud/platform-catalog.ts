export function platformTone(
  status: string,
): 'success' | 'warning' | 'danger' | 'info' | 'neutral' {
  if (['ERROR', 'FAILED', 'OFFLINE'].includes(status)) return 'danger';
  if (['WARNING', 'DEGRADED', 'MAINTENANCE', 'BLOCKED', 'RESTRICTED'].includes(status))
    return 'warning';
  if (['RUNNING', 'PROCESSING', 'PENDING'].includes(status)) return 'info';
  if (
    [
      'ENABLED',
      'CONFIRMED',
      'STARTED',
      'READY',
      'HEALTHY',
      'SUCCESS',
      'APPLIED',
      'ACTIVE',
      'ONLINE',
    ].includes(status)
  )
    return 'success';
  return 'neutral';
}

