const text = (
  key: string,
  label: string,
  description: string,
  extra: Partial<PlatformField> = {},
): PlatformField => ({ key, label, description, kind: 'text', form: true, ...extra });
const num = (
  key: string,
  label: string,
  unit = '',
  extra: Partial<PlatformField> = {},
): PlatformField =>
  text(key, label, `${label}${unit ? `, ${unit}` : ''}.`, {
    kind: 'number',
    unit,
    min: 0,
    ...extra,
  });
